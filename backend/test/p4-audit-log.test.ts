import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  createP4SyntheticAuditEvent, listP4SyntheticAuditEvents,
  P4AuditDeniedError, type P4AuditEvent, type P4AuditRepository,
} from "../src/platform/p4-audit-log.js";
const org = "10000000-0000-4000-8000-000000000001";
const owner = { orgId: org, orgSlug: "demo-orchid", userId: "user_demo_alice", verified: true as const, role: "OWNER" as const };
const member = { ...owner, userId: "user_demo_bob", role: "MEMBER" as const };
const id = "10000000-0000-4000-8000-000000000011";
function fixture(events: P4AuditEvent[] = []): P4AuditRepository {
  return {
    async append(event) { events.push({ ...event }); },
    async listByOrg(orgId, limit) { return events.filter(e => e.orgId === orgId).slice(0, limit); },
  };
}
describe("P4.19 safe append-only audit events", () => {
  it("generates redacted server-owned event with fixed action/object type", () => {
    // UUID generated by the factory is intentionally fixed for the test.
    const event = createP4SyntheticAuditEvent(owner, "membership.revoked", "user_demo_bob",
      2_000_000_000_000, () => id);
    assert.equal(event.orgId, org);
    assert.equal(event.before, "[REDACTED]");
    assert.equal(event.after, "[REDACTED]");
    assert.equal(event.objectType, "membership");
    assert.equal(event.actorUserId, owner.userId);
    assert.ok(!JSON.stringify(event).includes("access_token"));
  });
  it("allows owner read only; denies member and foreign tenant leaks", async () => {
    const event = createP4SyntheticAuditEvent(owner, "team.created", "team_demo_sales", 2_000_000_000_000, () => id);
    const repo = fixture([event]);
    assert.equal((await listP4SyntheticAuditEvents(owner, repo)).length, 1);
    await assert.rejects(listP4SyntheticAuditEvents(member, repo), P4AuditDeniedError);
    const malicious: P4AuditRepository = { ...repo,
      async listByOrg() { return [{ ...event, orgId: "10000000-0000-4000-8000-000000000002" }]; },
    };
    await assert.rejects(listP4SyntheticAuditEvents(owner, malicious), P4AuditDeniedError);
  });
  it("rejects injected action, object and tampered old/new values", async () => {
    assert.throws(() => createP4SyntheticAuditEvent(owner,
      "tokens.exfiltrated" as never, "user_demo_bob", 2_000_000_000_000, () => id), P4AuditDeniedError);
    assert.throws(() => createP4SyntheticAuditEvent(owner,
      "team.created", "someone@example.com", 2_000_000_000_000, () => id), P4AuditDeniedError);
    const event = createP4SyntheticAuditEvent(owner, "team.created", "team_demo_sales", 2_000_000_000_000, () => id);
    await assert.rejects(listP4SyntheticAuditEvents(owner, fixture([{ ...event, before: "SENSITIVE" as never }])), P4AuditDeniedError);
  });
});
